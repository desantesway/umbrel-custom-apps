def csrf():
    if "csrf" not in session:
        session["csrf"] = secrets.token_urlsafe(24)
    return session["csrf"]

@app.before_request
def protect_requests():
    if request.endpoint not in ("home", "login", "static") and not session.get("logged"):
        return redirect(url_for("home"))
    if request.method == "POST":
        expected = session.get("csrf", "")
        supplied = request.form.get("csrf", "")
        if not expected or not hmac.compare_digest(expected, supplied):
            abort(400, "Invalid request token")

def render_page(title, body, **kwargs):
    return render_template_string(BASE, title=title, body=body,
        logged=bool(session.get("logged")), csrf=csrf(), **kwargs)

def logged_in():
    return bool(session.get("logged"))

@app.get("/")
def home():
    vaults = []
    if logged_in():
        for p in sorted(ROOT.iterdir(), key=lambda x: x.name.lower()):
            if p.name == "Unlocked" or p.name.startswith(".") or not p.is_dir():
                continue
            if not (p / "gocryptfs.conf").is_file():
                continue
            mount = UNLOCKED / p.name
            vaults.append({"name": p.name, "open": os.path.ismount(mount)})
    return render_page("Home", render_template_string(HOME, logged=logged_in(),
        csrf=csrf(), vaults=vaults, root=str(ROOT), unlocked=str(UNLOCKED)))

@app.post("/login")
def login():
    if hmac.compare_digest(request.form.get("password", ""), APP_PASSWORD):
        session.clear()
        session["logged"] = True
        session["csrf"] = secrets.token_urlsafe(24)
    else:
        flash("Incorrect app password.")
    return redirect(url_for("home"))

@app.post("/logout")
def logout():
    session.clear()
    return redirect(url_for("home"))

def valid_name(name):
    return bool(re.fullmatch(r"[A-Za-z0-9_-]{1,48}", name or ""))

def mount_is_active(path):
    return os.path.ismount(path)

@app.post("/create")
def create_vault():
    name = request.form.get("name", "")
    password = request.form.get("password", "")
    if not valid_name(name) or len(password) < 8:
        flash("Use a vault name with letters, numbers, underscores or hyphens, and a password of at least 8 characters.")
        return redirect(url_for("home"))
    enc = ROOT / name
    mount = UNLOCKED / name
    if enc.exists():
        flash("A folder with that vault name already exists.")
        return redirect(url_for("home"))
    enc.mkdir(mode=0o700)
    mount.mkdir(mode=0o700, parents=True, exist_ok=True)
    try:
        result = subprocess.run(
            ["gocryptfs", "-init", "-passfile", "/dev/stdin", str(enc)],
            input=(password + "\n").encode(),
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=90, check=False
        )
        output = result.stdout.decode(errors="replace")
        if result.returncode != 0:
            flash("Vault initialization failed: " + output[-700:])
            return redirect(url_for("home"))
        # gocryptfs prints its recovery key during initialization. Display it once;
        # never write it to the app's persistent storage or logs.
        return render_page("Recovery key", render_template_string(r"""
        <section class="card"><h2>Vault created: {{ name }}</h2>
        <p><strong>Save this recovery key now.</strong> Keep it somewhere secure and separate from the Toshiba drive. Anyone with this key can recover the vault password.</p>
        <pre>{{ output }}</pre><p><a href="{{ url_for('home') }}">Return to Vault Manager</a></p></section>
        """, name=name, output=output))
    except Exception as e:
        flash("Could not create vault: " + str(e))
        return redirect(url_for("home"))

@app.post("/unlock/<name>")
def unlock_vault(name):
    if not valid_name(name): abort(404)
    enc, mount = ROOT / name, UNLOCKED / name
    if not (enc / "gocryptfs.conf").is_file(): abort(404)
    mount.mkdir(parents=True, exist_ok=True)
    if mount_is_active(mount):
        flash("Vault is already unlocked.")
        return redirect(url_for("home"))
    if any(mount.iterdir()):
        flash("The unlock folder is not empty. Move its contents elsewhere before unlocking.")
        return redirect(url_for("home"))
    password = request.form.get("password", "")
    try:
        proc = subprocess.Popen(
            ["gocryptfs", "-fg", "-allow_other", "-o", "uid=1000,gid=1000",
             "-passfile", "/dev/stdin", str(enc), str(mount)],
            stdin=subprocess.PIPE, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE
        )
        proc.stdin.write((password + "\n").encode())
        proc.stdin.close()
        with process_lock:
            mount_processes[name] = proc
        for _ in range(50):
            if mount_is_active(mount):
                flash("Vault unlocked.")
                return redirect(url_for("home"))
            if proc.poll() is not None:
                err = proc.stderr.read().decode(errors="replace")[-900:]
                raise RuntimeError(err or "gocryptfs exited unexpectedly")
            time.sleep(0.2)
        raise RuntimeError("Mount did not become ready. Check FUSE and shared mount propagation.")
    except Exception as e:
        flash("Could not unlock vault: " + str(e))
        return redirect(url_for("home"))

@app.post("/lock/<name>")
def lock_vault(name):
    if not valid_name(name): abort(404)
    mount = UNLOCKED / name
    if not mount_is_active(mount):
        flash("Vault is already locked.")
        return redirect(url_for("home"))
    result = subprocess.run(["fusermount3", "-u", str(mount)], capture_output=True, text=True)
    if result.returncode:
        flash("Could not lock vault. Close any files being used and try again: " + result.stderr[-500:])
    else:
        with process_lock:
            mount_processes.pop(name, None)
        flash("Vault locked.")
    return redirect(url_for("home"))

def safe_path(root, relative):
    candidate = (root / relative).resolve()
    if candidate != root and root not in candidate.parents:
        abort(403)
    return candidate

@app.get("/browse/<name>")
def browse(name):
    if not logged_in(): return redirect(url_for("home"))
    if not valid_name(name): abort(404)
    root = (UNLOCKED / name).resolve()
    if not mount_is_active(root): abort(404)
    relative = request.args.get("path", "")
    current = safe_path(root, relative)
    if not current.is_dir(): abort(404)
    items = []
    for p in sorted(current.iterdir(), key=lambda x: (not x.is_dir(), x.name.lower())):
        if p.is_symlink():
            continue
        items.append({"name": p.name, "is_dir": p.is_dir(), "rel": str(p.relative_to(root))})
    parent = str(Path(relative).parent) if relative and str(Path(relative).parent) != "." else None
    return render_page(name, render_template_string(BROWSE, name=name, items=items,
        display_path="/" + relative.strip("/"), parent=parent,
        encoded_path=quote(relative, safe="/"), csrf=csrf()))

@app.post("/upload/<name>")
def upload(name):
    if not valid_name(name): abort(404)
    root = (UNLOCKED / name).resolve()
    if not mount_is_active(root): abort(404)
    relative = request.args.get("path", "")
    target = safe_path(root, relative)
    if not target.is_dir(): abort(404)
    uploads = request.files.getlist("files")
    count = 0
    for item in uploads:
        filename = secure_filename(item.filename or "")
        if not filename or filename in (".", ".."):
            continue
        dest = target / filename
        if dest.exists():
            flash(f"Skipped {filename}: a file with that name already exists.")
            continue
        item.save(dest)
        count += 1
    if count:
        flash(f"Uploaded {count} file(s).")
    return redirect(url_for("browse", name=name, path=relative))

@app.get("/download/<name>/<path:rel>")
def download(name, rel):
    if not valid_name(name): abort(404)
    root = (UNLOCKED / name).resolve()
    if not mount_is_active(root): abort(404)
    candidate = safe_path(root, rel)
    if not candidate.is_file() or candidate.is_symlink(): abort(404)
    return send_file(candidate, as_attachment=True)

if __name__ == "__main__":
    app.run(host="0.0.0.0", port=PORT, threaded=True)
